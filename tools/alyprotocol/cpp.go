package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"io"
	"os"
	"regexp"
	"sort"
	"strings"
)

// CppConfig 对应 tools/alyprotocol/cpp.json。
type CppConfig struct {
	Types map[string]CppTypeConfig `json:"types"`
	Skip  []string                 `json:"skip"`
}

type CppTypeConfig struct {
	Name string `json:"name"`
}

var cppIdentRe = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_]*$`)

func (c *CppConfig) normalize() error {
	for defName, tc := range c.Types {
		if tc.Name == "" {
			tc.Name = defName
		}
		if !cppIdentRe.MatchString(tc.Name) {
			return fmt.Errorf("类型 %s 的 C++ 名称 %q 不是合法标识符", defName, tc.Name)
		}
		c.Types[defName] = tc
	}
	for _, name := range c.Skip {
		if !cppIdentRe.MatchString(name) {
			return fmt.Errorf("skip 含非法定义名 %q", name)
		}
	}
	return nil
}

// LoadCppConfig 严格读取 C++ 生成配置。
func LoadCppConfig(path string) (*CppConfig, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("读取配置 %s: %v", path, err)
	}
	dec := json.NewDecoder(bytes.NewReader(data))
	dec.DisallowUnknownFields()
	var cfg CppConfig
	if err := dec.Decode(&cfg); err != nil {
		return nil, fmt.Errorf("解析配置 %s: %v", path, err)
	}
	var extra struct{}
	if err := dec.Decode(&extra); err != io.EOF {
		return nil, fmt.Errorf("配置 %s 含多余内容", path)
	}
	if err := cfg.normalize(); err != nil {
		return nil, fmt.Errorf("配置 %s: %v", path, err)
	}
	return &cfg, nil
}

// RenderCpp 生成 models_gen.h。
func RenderCpp(s *Schema, cfg *CppConfig) (GeneratedFile, error) {
	if err := cfg.normalize(); err != nil {
		return GeneratedFile{}, err
	}
	if err := validateCppConfig(s, cfg); err != nil {
		return GeneratedFile{}, err
	}
	order, err := cppDependencyOrder(s, cfg)
	if err != nil {
		return GeneratedFile{}, err
	}

	var b strings.Builder
	b.WriteString("// Code generated by tools/alyprotocol from spec/aly-protocol.schema.json. DO NOT EDIT.\n")
	b.WriteString("// Regenerate: cd tools/alyprotocol && go run . -write\n\n")
	b.WriteString("#pragma once\n\n")
	b.WriteString("#include <string>\n")
	b.WriteString("#include <vector>\n\n")
	b.WriteString("#include \"json.h\"\n")
	b.WriteString("#include \"optional.h\"\n\n")
	b.WriteString("namespace aly {\n\n")

	for _, def := range order {
		tc := cfg.Types[def.Name]
		if strings.TrimSpace(def.Description) != "" {
			b.WriteString("/// " + strings.ReplaceAll(def.Description, "\n", "\n/// ") + "\n")
		}
		fmt.Fprintf(&b, "struct %s {\n", tc.Name)
		for _, p := range def.Properties {
			if strings.TrimSpace(p.Description) != "" {
				b.WriteString("    /// " + strings.ReplaceAll(p.Description, "\n", "\n    /// ") + "\n")
			}
			typ, err := cppType(cfg, p, !def.IsRequired(p.Name))
			if err != nil {
				return GeneratedFile{}, fmt.Errorf("%s.%s: %v", def.Name, p.Name, err)
			}
			fmt.Fprintf(&b, "    %s %s;\n", typ, p.Name)
		}
		b.WriteString("};\n\n")
	}

	for _, def := range order {
		fmt.Fprintf(&b, "void %sFromJson(const JsonValue& value, %s& out);\n", cfg.Types[def.Name].Name, cfg.Types[def.Name].Name)
	}
	b.WriteString("\n")

	for _, def := range order {
		tc := cfg.Types[def.Name]
		fmt.Fprintf(&b, "inline void %sFromJson(const JsonValue& value, %s& out) {\n", tc.Name, tc.Name)
		for _, p := range def.Properties {
			line, err := cppFromJson(cfg, def, p)
			if err != nil {
				return GeneratedFile{}, fmt.Errorf("%s.%s: %v", def.Name, p.Name, err)
			}
			fmt.Fprintf(&b, "    %s\n", line)
		}
		b.WriteString("}\n\n")
	}

	b.WriteString("} // namespace aly\n")
	return GeneratedFile{Name: "models_gen.h", Content: []byte(b.String())}, nil
}

func validateCppConfig(s *Schema, cfg *CppConfig) error {
	skip := make(map[string]bool, len(cfg.Skip))
	for _, name := range cfg.Skip {
		if s.Def(name) == nil {
			return fmt.Errorf("C++ 配置 skip 了不存在的定义 %q", name)
		}
		if _, both := cfg.Types[name]; both {
			return fmt.Errorf("定义 %q 不能同时出现在 types 和 skip 中", name)
		}
		skip[name] = true
	}
	for defName := range cfg.Types {
		if s.Def(defName) == nil {
			return fmt.Errorf("C++ 配置引用了 schema 中不存在的定义 %q", defName)
		}
	}
	var missing []string
	for _, defName := range s.DefNames() {
		if _, ok := cfg.Types[defName]; ok || skip[defName] {
			continue
		}
		missing = append(missing, defName)
	}
	if len(missing) > 0 {
		sort.Strings(missing)
		return fmt.Errorf("schema 定义未生成 C++ 类型也未 skip: %s", strings.Join(missing, ", "))
	}
	return nil
}

// cppDependencyOrder 按字段引用做拓扑排序，保证 struct 字段使用完整类型。
func cppDependencyOrder(s *Schema, cfg *CppConfig) ([]*Object, error) {
	byName := make(map[string]*Object, len(s.Defs))
	for _, def := range s.Defs {
		byName[def.Name] = def
	}
	state := make(map[string]int, len(s.Defs))
	var order []*Object
	var visit func(*Object) error
	visit = func(def *Object) error {
		switch state[def.Name] {
		case 1:
			return fmt.Errorf("schema 存在循环引用: %s", def.Name)
		case 2:
			return nil
		}
		state[def.Name] = 1
		for _, p := range def.Properties {
			for _, ref := range []string{p.Ref, p.ItemsRef} {
				if ref == "" {
					continue
				}
				target := byName[refName(ref)]
				if target == nil {
					return fmt.Errorf("%s 引用了不存在的定义 %q", def.Name, ref)
				}
				if isSkippedCpp(cfg, target.Name) {
					continue
				}
				if err := visit(target); err != nil {
					return err
				}
			}
		}
		state[def.Name] = 2
		if !isSkippedCpp(cfg, def.Name) {
			order = append(order, def)
		}
		return nil
	}
	for _, def := range s.Defs {
		if isSkippedCpp(cfg, def.Name) {
			continue
		}
		if err := visit(def); err != nil {
			return nil, err
		}
	}
	return order, nil
}

func isSkippedCpp(cfg *CppConfig, defName string) bool {
	for _, name := range cfg.Skip {
		if name == defName {
			return true
		}
	}
	return false
}

func cppType(cfg *CppConfig, p *Property, optional bool) (string, error) {
	var base string
	switch p.Type {
	case "":
		base = "JsonValue"
	case "string":
		base = "std::string"
	case "boolean":
		base = "bool"
	case "integer":
		base = "long long"
	case "number":
		base = "double"
	case "object":
		return withCppOptional(cfg.Types[refName(p.Ref)].Name, optional), nil
	case "array":
		var elem string
		if p.ItemsRef != "" {
			elem = cfg.Types[refName(p.ItemsRef)].Name
		} else {
			switch p.ItemsType {
			case "string":
				elem = "std::string"
			case "boolean":
				elem = "bool"
			case "integer":
				elem = "long long"
			case "number":
				elem = "double"
			default:
				return "", fmt.Errorf("不支持的数组元素类型 %q", p.ItemsType)
			}
		}
		return withCppOptional("std::vector<"+elem+">", optional), nil
	default:
		return "", fmt.Errorf("无法映射到 C++ 类型: type=%q", p.Type)
	}
	return withCppOptional(base, optional), nil
}

func withCppOptional(typ string, optional bool) string {
	if optional {
		return "Optional<" + typ + ">"
	}
	return typ
}

func cppFromJson(cfg *CppConfig, def *Object, p *Property) (string, error) {
	key := fmt.Sprintf("%q", p.Name)
	optional := !def.IsRequired(p.Name)
	switch p.Type {
	case "string":
		if optional {
			return fmt.Sprintf("out.%s = jsonOptString(value, %s);", p.Name, key), nil
		}
		return fmt.Sprintf("out.%s = jsonString(value, %s);", p.Name, key), nil
	case "boolean":
		if optional {
			return fmt.Sprintf("out.%s = jsonOptBool(value, %s);", p.Name, key), nil
		}
		return fmt.Sprintf("out.%s = jsonBool(value, %s, false);", p.Name, key), nil
	case "integer":
		if optional {
			return fmt.Sprintf("out.%s = jsonOptInt(value, %s);", p.Name, key), nil
		}
		return fmt.Sprintf("out.%s = jsonInt(value, %s, 0);", p.Name, key), nil
	case "number":
		if optional {
			return fmt.Sprintf("out.%s = jsonOptDouble(value, %s);", p.Name, key), nil
		}
		return fmt.Sprintf("out.%s = jsonDouble(value, %s, 0.0);", p.Name, key), nil
	case "object":
		name := cfg.Types[refName(p.Ref)].Name
		if optional {
			return fmt.Sprintf(
				"out.%s = jsonObject< %s >(value, %s, &%sFromJson);", p.Name, name, key, name), nil
		}
		return fmt.Sprintf(
			"out.%s = jsonObject< %s >(value, %s, &%sFromJson).value_or(%s());", p.Name, name, key, name, name), nil
	case "array":
		if p.ItemsRef != "" {
			elem := cfg.Types[refName(p.ItemsRef)].Name
			if optional {
				return fmt.Sprintf(
					"out.%s = jsonOptObjectList< %s >(value, %s, &%sFromJson);", p.Name, elem, key, elem), nil
			}
			return fmt.Sprintf(
				"out.%s = jsonObjectList< %s >(value, %s, &%sFromJson);", p.Name, elem, key, elem), nil
		}
		switch p.ItemsType {
		case "string":
			if optional {
				return fmt.Sprintf("out.%s = jsonOptStringList(value, %s);", p.Name, key), nil
			}
			return fmt.Sprintf("out.%s = jsonStringList(value, %s);", p.Name, key), nil
		case "boolean":
			return fmt.Sprintf("out.%s = jsonBoolList(value, %s);", p.Name, key), nil
		case "integer":
			return fmt.Sprintf("out.%s = jsonIntList(value, %s);", p.Name, key), nil
		case "number":
			return fmt.Sprintf("out.%s = jsonDoubleList(value, %s);", p.Name, key), nil
		}
	}
	return "", fmt.Errorf("无法生成 fromJson: type=%q", p.Type)
}
