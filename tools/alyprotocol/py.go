// PythonConfig 对应 tools/alyprotocol/python.json。
type PythonConfig struct {
	Types map[string]PythonTypeConfig `json:"types"`
	Skip  []string                    `json:"skip"`
}

type PythonTypeConfig struct {
	Name string `json:"name"`
}

var pyIdentRe = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_]*$`)

func (c *PythonConfig) normalize() error {
	for defName, tc := range c.Types {
		if tc.Name == "" {
			tc.Name = defName
		}
		if !pyIdentRe.MatchString(tc.Name) {
			return fmt.Errorf("类型 %s 的 Python 类名 %q 不是合法标识符", defName, tc.Name)
		}
		c.Types[defName] = tc
	}
	for _, name := range c.Skip {
		if !pyIdentRe.MatchString(name) {
			return fmt.Errorf("skip 含非法定义名 %q", name)
		}
	}
	return nil
}

// LoadPythonConfig 严格读取 Python 生成配置。
func LoadPythonConfig(path string) (*PythonConfig, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("读取配置 %s: %v", path, err)
	}
	dec := json.NewDecoder(bytes.NewReader(data))
	dec.DisallowUnknownFields()
	var cfg PythonConfig
	if err := dec.Decode(&cfg); err != nil {
		return nil, fmt.Errorf("解析配置 %s: %v", path, err)
	}
	var extra struct{}
	if err := dec.Decode(&extra); err != io.EOF {
		return nil, fmt.Errorf("配置 %s 含多余内容", path)
	}
	if err := cfg.normalize(); err != nil {
		return nil, fmt.Errorf("配置 %s: %v", path, err)
	}
	return &cfg, nil
}

// RenderPython 生成 alyclient/models_gen.py。
func RenderPython(s *Schema, cfg *PythonConfig) (GeneratedFile, error) {
	if err := cfg.normalize(); err != nil {
		return GeneratedFile{}, err
	}
	if err := validatePythonConfig(s, cfg); err != nil {
		return GeneratedFile{}, err
	}

	var b strings.Builder
	b.WriteString("# Code generated by tools/alyprotocol from spec/aly-protocol.schema.json. DO NOT EDIT.\n")
	b.WriteString("# Regenerate: cd tools/alyprotocol && go run . -write\n\n")
	b.WriteString("from __future__ import annotations\n\n")
	b.WriteString("from dataclasses import dataclass\n")
	b.WriteString("from typing import Optional\n\n")

	for _, def := range s.Defs {
		if isSkippedPython(cfg, def.Name) {
			continue
		}
		for _, p := range def.Properties {
			if len(p.Enum) == 0 {
				continue
			}
			for _, v := range p.Enum {
				fmt.Fprintf(&b, "%s = %q\n", pyEnumConst(def.Name, p.Name, v), v)
			}
			b.WriteString("\n")
		}
	}

	first := true
	for _, def := range s.Defs {
		if isSkippedPython(cfg, def.Name) {
			continue
		}
		if !first {
			b.WriteString("\n")
		}
		first = false
		tc := cfg.Types[def.Name]

		b.WriteString("@dataclass\nclass ")
		b.WriteString(tc.Name)
		b.WriteString(":\n")
		if strings.TrimSpace(def.Description) != "" {
			b.WriteString("    \"\"\"")
			b.WriteString(pyDoc(def.Description))
			b.WriteString("\"\"\"\n")
		}

		required, optional := splitRequiredOptional(def)
		for _, p := range required {
			if err := writePyField(&b, p, false); err != nil {
				return GeneratedFile{}, fmt.Errorf("%s.%s: %v", def.Name, p.Name, err)
			}
		}
		for _, p := range optional {
			if err := writePyField(&b, p, true); err != nil {
				return GeneratedFile{}, fmt.Errorf("%s.%s: %v", def.Name, p.Name, err)
			}
		}

		b.WriteString("\n    @classmethod\n")
		b.WriteString("    def from_dict(cls, data: dict) -> \"")
		b.WriteString(tc.Name)
		b.WriteString("\":\n")
		b.WriteString("        return cls(\n")
		ordered := append(append([]*Property{}, required...), optional...)
		for _, p := range ordered {
			expr, err := pyFromDict(def, p)
			if err != nil {
				return GeneratedFile{}, fmt.Errorf("%s.%s: %v", def.Name, p.Name, err)
			}
			fmt.Fprintf(&b, "            %s=%s,\n", p.Name, expr)
		}
		b.WriteString("        )\n")
	}

	return GeneratedFile{Name: "models_gen.py", Content: []byte(b.String())}, nil
}

func validatePythonConfig(s *Schema, cfg *PythonConfig) error {
	skip := make(map[string]bool, len(cfg.Skip))
	for _, name := range cfg.Skip {
		if s.Def(name) == nil {
			return fmt.Errorf("Python 配置 skip 了不存在的定义 %q", name)
		}
		if _, both := cfg.Types[name]; both {
			return fmt.Errorf("定义 %q 不能同时出现在 types 和 skip 中", name)
		}
		skip[name] = true
	}
	for defName := range cfg.Types {
		if s.Def(defName) == nil {
			return fmt.Errorf("Python 配置引用了 schema 中不存在的定义 %q", defName)
		}
	}
	var missing []string
	for _, defName := range s.DefNames() {
		if _, ok := cfg.Types[defName]; ok || skip[defName] {
			continue
		}
		missing = append(missing, defName)
	}
	if len(missing) > 0 {
		sort.Strings(missing)
		return fmt.Errorf("schema 定义未生成 Python 类也未 skip: %s", strings.Join(missing, ", "))
	}
	return nil
}

func isSkippedPython(cfg *PythonConfig, defName string) bool {
	for _, name := range cfg.Skip {
		if name == defName {
			return true
		}
	}
	return false
}

// splitRequiredOptional 把字段分成必填（无默认值）与可选（dataclass 要求默认值在后）。
func splitRequiredOptional(def *Object) (required, optional []*Property) {
	for _, p := range def.Properties {
		if def.IsRequired(p.Name) {
			required = append(required, p)
		} else {
			optional = append(optional, p)
		}
	}
	return required, optional
}

func writePyField(b *strings.Builder, p *Property, optional bool) error {
	if desc := strings.TrimSpace(p.Description); desc != "" {
		b.WriteString("    # " + strings.ReplaceAll(desc, "\n", " ") + "\n")
	}
	typ, err := pyType(p)
	if err != nil {
		return err
	}
	b.WriteString("    " + p.Name + ": ")
	if optional {
		b.WriteString("Optional[" + typ + "] = None\n")
	} else {
		b.WriteString(typ + "\n")
	}
	return nil
}

func pyType(p *Property) (string, error) {
	if len(p.Enum) > 0 {
		return "str", nil
	}
	switch p.Type {
	case "":
		return "object", nil
	case "string":
		return "str", nil
	case "boolean":
		return "bool", nil
	case "integer":
		return "int", nil
	case "number":
		return "float", nil
	case "object":
		return refName(p.Ref), nil
	case "array":
		if p.ItemsRef != "" {
			return "list[" + refName(p.ItemsRef) + "]", nil
		}
		switch p.ItemsType {
		case "string":
			return "list[str]", nil
		case "boolean":
			return "list[bool]", nil
		case "integer":
			return "list[int]", nil
		case "number":
			return "list[float]", nil
		}
	}
	return "", fmt.Errorf("无法映射到 Python 类型: type=%q", p.Type)
}

func pyFromDict(def *Object, p *Property) (string, error) {
	optional := !def.IsRequired(p.Name)
	key := fmt.Sprintf("%q", p.Name)
	value := "data.get(" + key + ")"
	guard := "data.get(" + key + ") is not None"

	if len(p.Enum) > 0 {
		return ternary(optional, "str("+value+")", guard), nil
	}
	switch p.Type {
	case "string":
		if optional {
			return "str(data[" + key + "]) if " + guard + " else None", nil
		}
		return "str(data.get(" + key + ", \"\"))", nil
	case "boolean":
		if optional {
			return "bool(data[" + key + "]) if " + guard + " else None", nil
		}
		return "bool(data.get(" + key + ", False))", nil
	case "integer":
		if optional {
			return "int(data[" + key + "]) if " + guard + " else None", nil
		}
		return "int(data.get(" + key + ", 0))", nil
	case "number":
		if optional {
			return "float(data[" + key + "]) if " + guard + " else None", nil
		}
		return "float(data.get(" + key + ", 0.0))", nil
	case "object":
		name := refName(p.Ref)
		if optional {
			return name + ".from_dict(data[" + key + "]) if " + guard + " else None", nil
		}
		return name + ".from_dict(data[" + key + "])", nil
	case "array":
		var item string
		if p.ItemsRef != "" {
			item = refName(p.ItemsRef) + ".from_dict(v)"
		} else {
			switch p.ItemsType {
			case "string":
				item = "str(v)"
			case "boolean":
				item = "bool(v)"
			case "integer":
				item = "int(v)"
			case "number":
				item = "float(v)"
			default:
				return "", fmt.Errorf("不支持的数组元素类型 %q", p.ItemsType)
			}
		}
		listExpr := "[" + item + " for v in (data.get(" + key + ") or [])]"
		if optional {
			return listExpr + " if " + guard + " else None", nil
		}
		return listExpr, nil
	}
	return "", fmt.Errorf("无法生成 from_dict: type=%q", p.Type)
}

func ternary(optional bool, value, guard string) string {
	if optional {
		return value + " if " + guard + " else None"
	}
	return value
}

func pyEnumConst(defName, propName, value string) string {
	parts := append(pyWords(defName), pyWords(propName)...)
	parts = append(parts, pyWords(value)...)
	return strings.Join(parts, "_")
}

// pyWords 按非字母数字分隔与驼峰边界切词，统一转大写。
func pyWords(s string) []string {
	var words []string
	var cur []rune
	flush := func() {
		if len(cur) == 0 {
			return
		}
		words = append(words, strings.ToUpper(string(cur)))
		cur = nil
	}
	for _, r := range s {
		if !unicode.IsLetter(r) && !unicode.IsDigit(r) {
			flush()
			continue
		}
		if unicode.IsUpper(r) && len(cur) > 0 {
			prev := cur[len(cur)-1]
			if unicode.IsLower(prev) || unicode.IsDigit(prev) {
				flush()
			}
		}
		cur = append(cur, r)
	}
	flush()
	return words
}

func pyDoc(desc string) string {
	desc = strings.ReplaceAll(desc, `"""`, `\"\"\"`)
	return strings.TrimSpace(desc)
}
