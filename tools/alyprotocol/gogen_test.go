package main

import (
	"os"
	"strings"
	"testing"
)

const goTestSchema = `{"$schema":"http://json-schema.org/draft-07/schema#","x-protocol-version":"1.0.0","$defs":{
"Output":{"type":"object","description":"信封","additionalProperties":false,
 "required":["isSuccess","errorMsg","data"],
 "properties":{"isSuccess":{"type":"boolean"},"errorMsg":{"type":"string"},"data":{}}},
"Item":{"type":"object","description":"条目","additionalProperties":false,
 "required":["path"],"properties":{"path":{"type":"string"}}},
"Data":{"type":"object","description":"数据","additionalProperties":false,
 "required":["status","count","items"],
 "properties":{"status":{"type":"string","enum":["BEGIN","DONE"],"description":"状态"},
 "count":{"type":"integer","description":"数量"},
 "optional_note":{"type":"string","description":"可选"},
 "items":{"type":"array","items":{"$ref":"#/$defs/Item"}},
 "tags":{"type":"array","items":{"type":"string"}}}}}}`

func goTestConfig() *GoConfig {
	return &GoConfig{
		Types: map[string]GoTypeConfig{"Item": {}, "Data": {}},
		Skip:  []string{"Output"},
	}
}

func TestRenderGoGeneratesStructsAndEnums(t *testing.T) {
	s := mustSchema(t, goTestSchema)
	file, err := RenderGo(s, goTestConfig())
	if err != nil {
		t.Fatal(err)
	}
	if file.Name != "models_gen.go" {
		t.Fatalf("file name = %q", file.Name)
	}
	out := string(file.Content)
	flat := strings.Join(strings.Fields(out), " ")
	for _, want := range []string{
		"// Code generated by tools/alyprotocol",
		"package alyclient",
		"type Data struct {",
		"Status DataStatus `json:\"status\"`",
		"type DataStatus string",
		`DataStatusDone DataStatus = "DONE"`,
		"Count int64 `json:\"count\"`",
		"OptionalNote string `json:\"optional_note\"`",
		"Items []Item `json:\"items\"`",
		"Tags []string `json:\"tags\"`",
	} {
		if !strings.Contains(flat, want) {
			t.Errorf("missing %q in:\n%s", want, out)
		}
	}
	if strings.Contains(out, "type Output struct") {
		t.Error("Output 应在 skip 中，不应生成")
	}
}

func TestRenderGoRequiresCoverage(t *testing.T) {
	s := mustSchema(t, goTestSchema)
	cfg := &GoConfig{Types: map[string]GoTypeConfig{}, Skip: []string{"Output"}}
	if _, err := RenderGo(s, cfg); err == nil {
		t.Fatal("expected coverage error")
	}
}

func TestRenderGoRejectsTypeAndSkipOverlap(t *testing.T) {
	s := mustSchema(t, goTestSchema)
	cfg := goTestConfig()
	cfg.Skip = append(cfg.Skip, "Data")
	if _, err := RenderGo(s, cfg); err == nil {
		t.Fatal("expected overlap error")
	}
}

func TestLoadGoConfigStrictAndDefaults(t *testing.T) {
	dir := t.TempDir()
	path := dir + "/go.json"
	if err := os.WriteFile(path, []byte(`{"types":{"Data":{}},"skip":["Output"],"extra":1}`), 0o600); err != nil {
		t.Fatal(err)
	}
	if _, err := LoadGoConfig(path); err == nil {
		t.Fatal("expected unknown-field error")
	}
	if err := os.WriteFile(path, []byte(`{"types":{"Data":{}},"skip":["Output"]}`), 0o600); err != nil {
		t.Fatal(err)
	}
	cfg, err := LoadGoConfig(path)
	if err != nil {
		t.Fatal(err)
	}
	if cfg.Types["Data"].Name != "Data" {
		t.Fatalf("default name = %q", cfg.Types["Data"].Name)
	}
}
