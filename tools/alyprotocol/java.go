package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"io"
	"os"
	"regexp"
	"sort"
	"strings"
)

// JavaConfig 对应 tools/alyprotocol/java.json。
type JavaConfig struct {
	Types map[string]JavaTypeConfig `json:"types"`
	Skip  []string                  `json:"skip"`
}

type JavaTypeConfig struct {
	Name string `json:"name"`
}

var javaIdentRe = regexp.MustCompile(`^[A-Za-z_$][A-Za-z0-9_$]*$`)

const javaPackage = "io.github.lishuangquan1987.alyclient.models"

func (c *JavaConfig) normalize() error {
	for defName, tc := range c.Types {
		if tc.Name == "" {
			tc.Name = defName
		}
		if !javaIdentRe.MatchString(tc.Name) {
			return fmt.Errorf("类型 %s 的 Java 类名 %q 不是合法标识符", defName, tc.Name)
		}
		c.Types[defName] = tc
	}
	for _, name := range c.Skip {
		if !javaIdentRe.MatchString(name) {
			return fmt.Errorf("skip 含非法定义名 %q", name)
		}
	}
	return nil
}

// LoadJavaConfig 严格读取 Java 生成配置。
func LoadJavaConfig(path string) (*JavaConfig, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("读取配置 %s: %v", path, err)
	}
	dec := json.NewDecoder(bytes.NewReader(data))
	dec.DisallowUnknownFields()
	var cfg JavaConfig
	if err := dec.Decode(&cfg); err != nil {
		return nil, fmt.Errorf("解析配置 %s: %v", path, err)
	}
	var extra struct{}
	if err := dec.Decode(&extra); err != io.EOF {
		return nil, fmt.Errorf("配置 %s 含多余内容", path)
	}
	if err := cfg.normalize(); err != nil {
		return nil, fmt.Errorf("配置 %s: %v", path, err)
	}
	return &cfg, nil
}

// RenderJava 为每个 schema 定义生成一个 Java 类文件。
func RenderJava(s *Schema, cfg *JavaConfig) ([]GeneratedFile, error) {
	if err := cfg.normalize(); err != nil {
		return nil, err
	}
	if err := validateJavaConfig(s, cfg); err != nil {
		return nil, err
	}

	var files []GeneratedFile
	for _, def := range s.Defs {
		if isSkippedJava(cfg, def.Name) {
			continue
		}
		content, err := renderJavaClass(s, cfg, def)
		if err != nil {
			return nil, err
		}
		files = append(files, GeneratedFile{
			Name:    cfg.Types[def.Name].Name + ".java",
			Content: []byte(content),
		})
	}
	return files, nil
}

func validateJavaConfig(s *Schema, cfg *JavaConfig) error {
	skip := make(map[string]bool, len(cfg.Skip))
	for _, name := range cfg.Skip {
		if s.Def(name) == nil {
			return fmt.Errorf("Java 配置 skip 了不存在的定义 %q", name)
		}
		if _, both := cfg.Types[name]; both {
			return fmt.Errorf("定义 %q 不能同时出现在 types 和 skip 中", name)
		}
		skip[name] = true
	}
	for defName := range cfg.Types {
		if s.Def(defName) == nil {
			return fmt.Errorf("Java 配置引用了 schema 中不存在的定义 %q", defName)
		}
	}
	var missing []string
	for _, defName := range s.DefNames() {
		if _, ok := cfg.Types[defName]; ok || skip[defName] {
			continue
		}
		missing = append(missing, defName)
	}
	if len(missing) > 0 {
		sort.Strings(missing)
		return fmt.Errorf("schema 定义未生成 Java 类也未 skip: %s", strings.Join(missing, ", "))
	}
	return nil
}

func isSkippedJava(cfg *JavaConfig, defName string) bool {
	for _, name := range cfg.Skip {
		if name == defName {
			return true
		}
	}
	return false
}

func renderJavaClass(s *Schema, cfg *JavaConfig, def *Object) (string, error) {
	tc := cfg.Types[def.Name]
	var b strings.Builder
	b.WriteString("// Code generated by tools/alyprotocol from spec/aly-protocol.schema.json. DO NOT EDIT.\n")
	b.WriteString("// Regenerate: cd tools/alyprotocol && go run . -write\n\n")
	fmt.Fprintf(&b, "package %s;\n\n", javaPackage)
	b.WriteString("import io.github.lishuangquan1987.alyclient.Json;\n")
	b.WriteString("import java.util.List;\n")
	b.WriteString("import java.util.Map;\n\n")

	if strings.TrimSpace(def.Description) != "" {
		b.WriteString("/** " + javaDoc(def.Description) + " */\n")
	}
	fmt.Fprintf(&b, "public final class %s {\n", tc.Name)
	for _, p := range def.Properties {
		for _, v := range p.Enum {
			fmt.Fprintf(&b, "    public static final String %s = %q;\n", javaEnumConst(p.Name, v), v)
		}
		if len(p.Enum) > 0 {
			b.WriteString("\n")
		}
	}
	for _, p := range def.Properties {
		if strings.TrimSpace(p.Description) != "" {
			b.WriteString("    // " + strings.ReplaceAll(p.Description, "\n", " ") + "\n")
		}
		typ, err := javaType(s, cfg, p, !def.IsRequired(p.Name))
		if err != nil {
			return "", fmt.Errorf("%s.%s: %v", def.Name, p.Name, err)
		}
		fmt.Fprintf(&b, "    public %s %s;\n", typ, javaField(p.Name))
	}
	b.WriteString("\n")
	fmt.Fprintf(&b, "    public static %s fromMap(Map<String, Object> data) {\n", tc.Name)
	fmt.Fprintf(&b, "        %s value = new %s();\n", tc.Name, tc.Name)
	for _, p := range def.Properties {
		expr, err := javaFromMap(s, cfg, def, p)
		if err != nil {
			return "", fmt.Errorf("%s.%s: %v", def.Name, p.Name, err)
		}
		fmt.Fprintf(&b, "        value.%s = %s;\n", javaField(p.Name), expr)
	}
	b.WriteString("        return value;\n")
	b.WriteString("    }\n")
	b.WriteString("}\n")
	return b.String(), nil
}

func javaType(s *Schema, cfg *JavaConfig, p *Property, optional bool) (string, error) {
	switch p.Type {
	case "":
		return "Object", nil
	case "string":
		return "String", nil
	case "boolean":
		if optional {
			return "Boolean", nil
		}
		return "boolean", nil
	case "integer":
		if optional {
			return "Long", nil
		}
		return "long", nil
	case "number":
		if optional {
			return "Double", nil
		}
		return "double", nil
	case "object":
		return cfg.Types[refName(p.Ref)].Name, nil
	case "array":
		if p.ItemsRef != "" {
			return "List<" + cfg.Types[refName(p.ItemsRef)].Name + ">", nil
		}
		return "List<" + javaPrimitiveBox(p.ItemsType) + ">", nil
	}
	return "", fmt.Errorf("无法映射到 Java 类型: type=%q", p.Type)
}

func javaPrimitiveBox(t string) string {
	switch t {
	case "string":
		return "String"
	case "boolean":
		return "Boolean"
	case "integer":
		return "Long"
	case "number":
		return "Double"
	}
	return "Object"
}

func javaFromMap(s *Schema, cfg *JavaConfig, def *Object, p *Property) (string, error) {
	key := fmt.Sprintf("%q", p.Name)
	optional := !def.IsRequired(p.Name)
	if len(p.Enum) > 0 {
		if optional {
			return "Json.optStr(data, " + key + ")", nil
		}
		return "Json.str(data, " + key + ")", nil
	}
	switch p.Type {
	case "string":
		if optional {
			return "Json.optStr(data, " + key + ")", nil
		}
		return "Json.str(data, " + key + ")", nil
	case "boolean":
		if optional {
			return "Json.optBool(data, " + key + ")", nil
		}
		return "Json.bool(data, " + key + ", false)", nil
	case "integer":
		if optional {
			return "Json.optLng(data, " + key + ")", nil
		}
		return "Json.lng(data, " + key + ", 0L)", nil
	case "number":
		if optional {
			return "Json.optDbl(data, " + key + ")", nil
		}
		return "Json.dbl(data, " + key + ", 0.0)", nil
	case "object":
		name := cfg.Types[refName(p.Ref)].Name
		if optional {
			return "Json.map(data, " + key + ") == null ? null : " + name + ".fromMap(Json.map(data, " + key + "))", nil
		}
		return name + ".fromMap(Json.map(data, " + key + "))", nil
	case "array":
		if p.ItemsRef != "" {
			elem := cfg.Types[refName(p.ItemsRef)].Name
			fn := "Json.mapList(data, " + key + ", " + elem + "::fromMap)"
			if optional {
				return "Json.optMapList(data, " + key + ", " + elem + "::fromMap)", nil
			}
			return fn, nil
		}
		switch p.ItemsType {
		case "string":
			if optional {
				return "Json.optStrList(data, " + key + ")", nil
			}
			return "Json.strList(data, " + key + ")", nil
		case "boolean":
			return "Json.boolList(data, " + key + ")", nil
		case "integer":
			return "Json.lngList(data, " + key + ")", nil
		case "number":
			return "Json.dblList(data, " + key + ")", nil
		}
	}
	return "", fmt.Errorf("无法生成 fromMap: type=%q", p.Type)
}

func javaField(name string) string {
	parts := strings.Split(name, "_")
	for i := 1; i < len(parts); i++ {
		if parts[i] == "" {
			continue
		}
		parts[i] = strings.ToUpper(parts[i][:1]) + parts[i][1:]
	}
	if len(parts[0]) == 0 {
		return name
	}
	return strings.ToLower(parts[0][:1]) + parts[0][1:] + strings.Join(parts[1:], "")
}

func javaEnumConst(propName, value string) string {
	return strings.ToUpper(propName) + "_" + strings.ToUpper(value)
}

func javaDoc(desc string) string {
	return strings.ReplaceAll(strings.TrimSpace(desc), "*/", "*\\/")
}
