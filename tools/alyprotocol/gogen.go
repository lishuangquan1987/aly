package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"io"
	"os"
	"regexp"
	"sort"
	"strings"
)

// GoConfig 对应 tools/alyprotocol/go.json。
type GoConfig struct {
	Types map[string]GoTypeConfig `json:"types"`
	Skip  []string                `json:"skip"`
}

type GoTypeConfig struct {
	Name string `json:"name"`
}

var goIdentRe = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_]*$`)

func (c *GoConfig) normalize() error {
	for defName, tc := range c.Types {
		if tc.Name == "" {
			tc.Name = defName
		}
		if !goIdentRe.MatchString(tc.Name) {
			return fmt.Errorf("类型 %s 的 Go 名称 %q 不是合法标识符", defName, tc.Name)
		}
		c.Types[defName] = tc
	}
	for _, name := range c.Skip {
		if !goIdentRe.MatchString(name) {
			return fmt.Errorf("skip 含非法定义名 %q", name)
		}
	}
	return nil
}

// LoadGoConfig 严格读取 Go 生成配置。
func LoadGoConfig(path string) (*GoConfig, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("读取配置 %s: %v", path, err)
	}
	dec := json.NewDecoder(bytes.NewReader(data))
	dec.DisallowUnknownFields()
	var cfg GoConfig
	if err := dec.Decode(&cfg); err != nil {
		return nil, fmt.Errorf("解析配置 %s: %v", path, err)
	}
	var extra struct{}
	if err := dec.Decode(&extra); err != io.EOF {
		return nil, fmt.Errorf("配置 %s 含多余内容", path)
	}
	if err := cfg.normalize(); err != nil {
		return nil, fmt.Errorf("配置 %s: %v", path, err)
	}
	return &cfg, nil
}

// RenderGo 生成单个 models_gen.go；要求每个 schema 定义要么生成、要么显式 skip。
func RenderGo(s *Schema, cfg *GoConfig) (GeneratedFile, error) {
	if err := cfg.normalize(); err != nil {
		return GeneratedFile{}, err
	}
	if err := validateGoConfig(s, cfg); err != nil {
		return GeneratedFile{}, err
	}

	var b strings.Builder
	b.WriteString("// Code generated by tools/alyprotocol from spec/aly-protocol.schema.json. DO NOT EDIT.\n")
	b.WriteString("// Regenerate: cd tools/alyprotocol && go run . -write\n\n")
	b.WriteString("package alyclient\n")

	first := true
	for _, def := range s.Defs {
		if isSkippedGo(cfg, def.Name) {
			continue
		}
		tc := cfg.Types[def.Name]
		if !first {
			b.WriteString("\n")
		}
		first = false

		for _, p := range def.Properties {
			if len(p.Enum) == 0 {
				continue
			}
			enumName := goEnumName(tc.Name, p.Name)
			fmt.Fprintf(&b, "type %s string\n\nconst (\n", enumName)
			for _, value := range p.Enum {
				fmt.Fprintf(&b, "\t%s%s %s = %q\n", enumName, enumCase(value), enumName, value)
			}
			b.WriteString(")\n\n")
		}

		writeGoDoc(&b, "", def.Description)
		fmt.Fprintf(&b, "type %s struct {\n", tc.Name)
		for _, p := range def.Properties {
			writeGoDoc(&b, "\t", p.Description)
			typ, err := goType(s, cfg, def, p)
			if err != nil {
				return GeneratedFile{}, fmt.Errorf("%s.%s: %v", def.Name, p.Name, err)
			}
			fmt.Fprintf(&b, "\t%s %s `json:\"%s\"`\n", pascalCase(p.Name), typ, p.Name)
		}
		b.WriteString("}\n")
	}

	formatted, err := format.Source([]byte(b.String()))
	if err != nil {
		return GeneratedFile{}, fmt.Errorf("生成的 Go 代码无法格式化: %v\n%s", err, b.String())
	}
	return GeneratedFile{Name: "models_gen.go", Content: formatted}, nil
}

func validateGoConfig(s *Schema, cfg *GoConfig) error {
	skip := make(map[string]bool, len(cfg.Skip))
	for _, name := range cfg.Skip {
		if s.Def(name) == nil {
			return fmt.Errorf("Go 配置 skip 了不存在的定义 %q", name)
		}
		if _, both := cfg.Types[name]; both {
			return fmt.Errorf("定义 %q 不能同时出现在 types 和 skip 中", name)
		}
		skip[name] = true
	}
	for defName := range cfg.Types {
		if s.Def(defName) == nil {
			return fmt.Errorf("Go 配置引用了 schema 中不存在的定义 %q", defName)
		}
	}
	var missing []string
	for _, defName := range s.DefNames() {
		if _, ok := cfg.Types[defName]; ok || skip[defName] {
			continue
		}
		missing = append(missing, defName)
	}
	if len(missing) > 0 {
		sort.Strings(missing)
		return fmt.Errorf("schema 定义未生成 Go 类型也未 skip: %s", strings.Join(missing, ", "))
	}
	return nil
}

func isSkippedGo(cfg *GoConfig, defName string) bool {
	for _, name := range cfg.Skip {
		if name == defName {
			return true
		}
	}
	return false
}

func goType(s *Schema, cfg *GoConfig, def *Object, p *Property) (string, error) {
	if len(p.Enum) > 0 {
		return goEnumName(cfg.Types[def.Name].Name, p.Name), nil
	}
	switch p.Type {
	case "":
		return "any", nil
	case "string":
		return "string", nil
	case "boolean":
		return "bool", nil
	case "integer":
		return "int64", nil
	case "number":
		return "float64", nil
	case "object":
		if p.Ref == "" {
			return "", fmt.Errorf("object 必须用 $ref 指定定义")
		}
		return goRefName(cfg, p.Ref)
	case "array":
		var elem string
		if p.ItemsRef != "" {
			name, err := goRefName(cfg, p.ItemsRef)
			if err != nil {
				return "", err
			}
			elem = name
		} else {
			switch p.ItemsType {
			case "string":
				elem = "string"
			case "boolean":
				elem = "bool"
			case "integer":
				elem = "int64"
			case "number":
				elem = "float64"
			default:
				return "", fmt.Errorf("不支持的数组元素类型 %q", p.ItemsType)
			}
		}
		return "[]" + elem, nil
	}
	return "", fmt.Errorf("无法映射到 Go 类型: type=%q", p.Type)
}

func goRefName(cfg *GoConfig, ref string) (string, error) {
	defName := strings.TrimPrefix(ref, "#/$defs/")
	tc, ok := cfg.Types[defName]
	if !ok {
		return "", fmt.Errorf("$ref 指向未生成的 Go 定义 %q", defName)
	}
	return tc.Name, nil
}

func goEnumName(typeName, propName string) string {
	return typeName + pascalCase(propName)
}

// enumCase 把协议枚举值（全大写或小写）转成 Go 常量后缀：BEGIN -> Begin，keep -> Keep。
func enumCase(value string) string {
	lower := strings.ToLower(value)
	if lower == "" {
		return ""
	}
	return strings.ToUpper(lower[:1]) + lower[1:]
}

func writeGoDoc(b *strings.Builder, indent, desc string) {
	desc = strings.TrimSpace(desc)
	if desc == "" {
		return
	}
	for _, line := range strings.Split(desc, "\n") {
		b.WriteString(indent + "// " + strings.TrimSpace(line) + "\n")
	}
}
