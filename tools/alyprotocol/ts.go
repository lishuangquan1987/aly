package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"io"
	"os"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

// TSConfig 对应 tools/alyprotocol/ts.json：C# 之外的 TypeScript 模型生成配置。
type TSConfig struct {
	Types map[string]TSTypeConfig `json:"types"`
}

// TSTypeConfig 只允许改接口名；TS SDK 生成全部协议定义，不做裁剪。
type TSTypeConfig struct {
	Name string `json:"name"`
}

var tsIdentRe = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_]*$`)

func (c *TSConfig) normalize() error {
	for defName, tc := range c.Types {
		if tc.Name == "" {
			tc.Name = defName
		}
		if !tsIdentRe.MatchString(tc.Name) {
			return fmt.Errorf("类型 %s 的 TS 名称 %q 不是合法标识符", defName, tc.Name)
		}
		c.Types[defName] = tc
	}
	return nil
}

// LoadTSConfig 严格读取 TS 生成配置。
func LoadTSConfig(path string) (*TSConfig, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("读取配置 %s: %v", path, err)
	}
	dec := json.NewDecoder(bytes.NewReader(data))
	dec.DisallowUnknownFields()
	var cfg TSConfig
	if err := dec.Decode(&cfg); err != nil {
		return nil, fmt.Errorf("解析配置 %s: %v", path, err)
	}
	var extra struct{}
	if err := dec.Decode(&extra); err != io.EOF {
		return nil, fmt.Errorf("配置 %s 含多余内容", path)
	}
	if err := cfg.normalize(); err != nil {
		return nil, fmt.Errorf("配置 %s: %v", path, err)
	}
	return &cfg, nil
}

// RenderTS 生成单个 models.ts；要求 schema 的每个定义都有 TS 接口（防止新增命令漏生成）。
func RenderTS(s *Schema, cfg *TSConfig) (GeneratedFile, error) {
	if err := cfg.normalize(); err != nil {
		return GeneratedFile{}, err
	}
	if err := validateTSConfig(s, cfg); err != nil {
		return GeneratedFile{}, err
	}

	var b strings.Builder
	b.WriteString("// <auto-generated>\n")
	b.WriteString("// 本文件由 tools/alyprotocol 从 spec/aly-protocol.schema.json 生成，请勿手工编辑。\n")
	b.WriteString("// 重新生成：cd tools/alyprotocol && go run . -write\n")
	b.WriteString("// </auto-generated>\n\n")

	for i, def := range s.Defs {
		tc := cfg.Types[def.Name]
		if i > 0 {
			b.WriteString("\n")
		}
		writeTSDoc(&b, "", def.Description)
		b.WriteString("export interface ")
		b.WriteString(tc.Name)
		b.WriteString(" {\n")
		for _, p := range def.Properties {
			writeTSDoc(&b, "  ", p.Description)
			b.WriteString("  ")
			b.WriteString(p.Name)
			if !def.IsRequired(p.Name) {
				b.WriteString("?")
			}
			b.WriteString(": ")
			typ, err := tsType(s, cfg, p)
			if err != nil {
				return GeneratedFile{}, fmt.Errorf("%s.%s: %v", def.Name, p.Name, err)
			}
			b.WriteString(typ)
			b.WriteString(";\n")
		}
		b.WriteString("}\n")
	}
	return GeneratedFile{Name: "models.ts", Content: []byte(b.String())}, nil
}

func validateTSConfig(s *Schema, cfg *TSConfig) error {
	for defName := range cfg.Types {
		if s.Def(defName) == nil {
			return fmt.Errorf("TS 配置引用了 schema 中不存在的定义 %q", defName)
		}
	}
	missing := make([]string, 0)
	for _, defName := range s.DefNames() {
		if _, ok := cfg.Types[defName]; !ok {
			missing = append(missing, defName)
		}
	}
	if len(missing) > 0 {
		sort.Strings(missing)
		return fmt.Errorf("schema 定义未生成 TS 接口: %s", strings.Join(missing, ", "))
	}
	return nil
}

func tsType(s *Schema, cfg *TSConfig, p *Property) (string, error) {
	switch p.Type {
	case "":
		return "unknown", nil
	case "string":
		if len(p.Enum) > 0 {
			parts := make([]string, len(p.Enum))
			for i, v := range p.Enum {
				parts[i] = strconv.Quote(v)
			}
			return strings.Join(parts, " | "), nil
		}
		return "string", nil
	case "boolean":
		return "boolean", nil
	case "integer", "number":
		return "number", nil
	case "object":
		if p.Ref == "" {
			return "", fmt.Errorf("object 必须用 $ref 指定定义")
		}
		return tsRefName(cfg, p.Ref)
	case "array":
		var elem string
		if p.ItemsRef != "" {
			name, err := tsRefName(cfg, p.ItemsRef)
			if err != nil {
				return "", err
			}
			elem = name
		} else {
			switch p.ItemsType {
			case "string":
				elem = "string"
			case "boolean":
				elem = "boolean"
			case "integer", "number":
				elem = "number"
			default:
				return "", fmt.Errorf("不支持的数组元素类型 %q", p.ItemsType)
			}
		}
		if strings.Contains(elem, " | ") {
			elem = "(" + elem + ")"
		}
		return elem + "[]", nil
	}
	return "", fmt.Errorf("无法映射到 TS 类型: type=%q", p.Type)
}

func tsRefName(cfg *TSConfig, ref string) (string, error) {
	defName := strings.TrimPrefix(ref, "#/$defs/")
	tc, ok := cfg.Types[defName]
	if !ok {
		return "", fmt.Errorf("$ref 指向未生成的 TS 定义 %q", defName)
	}
	return tc.Name, nil
}

func writeTSDoc(b *strings.Builder, indent, desc string) {
	desc = strings.TrimSpace(desc)
	if desc == "" {
		return
	}
	escaped := strings.ReplaceAll(desc, "*/", "*\\/")
	lines := strings.Split(escaped, "\n")
	if len(lines) == 1 {
		b.WriteString(indent + "/** " + lines[0] + " */\n")
		return
	}
	b.WriteString(indent + "/**\n")
	for _, line := range lines {
		b.WriteString(indent + " * " + strings.TrimSpace(line) + "\n")
	}
	b.WriteString(indent + " */\n")
}
