// PascalConfig 对应 tools/alyprotocol/pascal.json。
type PascalConfig struct {
	Types map[string]PascalTypeConfig `json:"types"`
	Skip  []string                    `json:"skip"`
}

type PascalTypeConfig struct {
	Name string `json:"name"`
}

var pascalIdentRe = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_]*$`)

func (c *PascalConfig) normalize() error {
	for defName, tc := range c.Types {
		if tc.Name == "" {
			tc.Name = "T" + defName
		}
		if !pascalIdentRe.MatchString(tc.Name) {
			return fmt.Errorf("类型 %s 的 Pascal 名称 %q 不是合法标识符", defName, tc.Name)
		}
		c.Types[defName] = tc
	}
	for _, name := range c.Skip {
		if !pascalIdentRe.MatchString(name) {
			return fmt.Errorf("skip 含非法定义名 %q", name)
		}
	}
	return nil
}

// LoadPascalConfig 严格读取 Pascal 生成配置。
func LoadPascalConfig(path string) (*PascalConfig, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("读取配置 %s: %v", path, err)
	}
	dec := json.NewDecoder(bytes.NewReader(data))
	dec.DisallowUnknownFields()
	var cfg PascalConfig
	if err := dec.Decode(&cfg); err != nil {
		return nil, fmt.Errorf("解析配置 %s: %v", path, err)
	}
	var extra struct{}
	if err := dec.Decode(&extra); err != io.EOF {
		return nil, fmt.Errorf("配置 %s 含多余内容", path)
	}
	if err := cfg.normalize(); err != nil {
		return nil, fmt.Errorf("配置 %s: %v", path, err)
	}
	return &cfg, nil
}

// RenderPascal 生成 models_gen.pas。
func RenderPascal(s *Schema, cfg *PascalConfig) (GeneratedFile, error) {
	if err := cfg.normalize(); err != nil {
		return GeneratedFile{}, err
	}
	if err := validatePascalConfig(s, cfg); err != nil {
		return GeneratedFile{}, err
	}
	order, err := pascalDependencyOrder(s, cfg)
	if err != nil {
		return GeneratedFile{}, err
	}

	var b strings.Builder
	b.WriteString("// Code generated by tools/alyprotocol from spec/aly-protocol.schema.json. DO NOT EDIT.\n")
	b.WriteString("// Regenerate: cd tools/alyprotocol && go run . -write\n\n")
	b.WriteString("unit models_gen;\n\n")
	b.WriteString("{$mode delphi}{$H+}\n\n")
	b.WriteString("interface\n\n")
	b.WriteString("uses\n  fpjson, jsonhelp;\n\n")
	b.WriteString("type\n")

	for _, def := range order {
		tc := cfg.Types[def.Name]
		if strings.TrimSpace(def.Description) != "" {
			b.WriteString("  { " + strings.ReplaceAll(def.Description, "\n", " ") + " }\n")
		}
		fmt.Fprintf(&b, "  %s = record\n", tc.Name)
		for _, p := range def.Properties {
			if strings.TrimSpace(p.Description) != "" {
				b.WriteString("    { " + strings.ReplaceAll(p.Description, "\n", " ") + " }\n")
			}
			typ, err := pascalType(cfg, p)
			if err != nil {
				return GeneratedFile{}, fmt.Errorf("%s.%s: %v", def.Name, p.Name, err)
			}
			fmt.Fprintf(&b, "    %s: %s;\n", pascalField(p.Name), typ)
		}
		b.WriteString("  end;\n\n")
	}

	b.WriteString("\n")
	for _, def := range order {
		fmt.Fprintf(
			&b,
			"function %sFromJson(Value: TJSONObject): %s;\n",
			cfg.Types[def.Name].Name,
			cfg.Types[def.Name].Name,
		)
	}
	b.WriteString("\nimplementation\n\n")

	for _, def := range order {
		tc := cfg.Types[def.Name]
		fmt.Fprintf(&b, "function %sFromJson(Value: TJSONObject): %s;\n", tc.Name, tc.Name)
		varDecls := pascalLocalVars(cfg, def)
		if len(varDecls) > 0 {
			b.WriteString("var\n")
			for _, decl := range varDecls {
				b.WriteString("  " + decl + "\n")
			}
		}
		b.WriteString("begin\n")
		for _, p := range def.Properties {
			lines, err := pascalFromJson(cfg, def, p)
			if err != nil {
				return GeneratedFile{}, fmt.Errorf("%s.%s: %v", def.Name, p.Name, err)
			}
			for _, line := range lines {
				b.WriteString("  " + line + "\n")
			}
		}
		b.WriteString("end;\n\n")
	}

	b.WriteString("end.\n")
	return GeneratedFile{Name: "models_gen.pas", Content: []byte(b.String())}, nil
}

func validatePascalConfig(s *Schema, cfg *PascalConfig) error {
	skip := make(map[string]bool, len(cfg.Skip))
	for _, name := range cfg.Skip {
		if s.Def(name) == nil {
			return fmt.Errorf("Pascal 配置 skip 了不存在的定义 %q", name)
		}
		if _, both := cfg.Types[name]; both {
			return fmt.Errorf("定义 %q 不能同时出现在 types 和 skip 中", name)
		}
		skip[name] = true
	}
	for defName := range cfg.Types {
		if s.Def(defName) == nil {
			return fmt.Errorf("Pascal 配置引用了 schema 中不存在的定义 %q", defName)
		}
	}
	var missing []string
	for _, defName := range s.DefNames() {
		if _, ok := cfg.Types[defName]; ok || skip[defName] {
			continue
		}
		missing = append(missing, defName)
	}
	if len(missing) > 0 {
		sort.Strings(missing)
		return fmt.Errorf("schema 定义未生成 Pascal 类型也未 skip: %s", strings.Join(missing, ", "))
	}
	return nil
}

func pascalDependencyOrder(s *Schema, cfg *PascalConfig) ([]*Object, error) {
	byName := make(map[string]*Object, len(s.Defs))
	for _, def := range s.Defs {
		byName[def.Name] = def
	}
	state := make(map[string]int, len(s.Defs))
	var order []*Object
	var visit func(*Object) error
	visit = func(def *Object) error {
		switch state[def.Name] {
		case 1:
			return fmt.Errorf("schema 存在循环引用: %s", def.Name)
		case 2:
			return nil
		}
		state[def.Name] = 1
		for _, p := range def.Properties {
			for _, ref := range []string{p.Ref, p.ItemsRef} {
				if ref == "" {
					continue
				}
				target := byName[refName(ref)]
				if target == nil {
					return fmt.Errorf("%s 引用了不存在的定义 %q", def.Name, ref)
				}
				if isSkippedPascal(cfg, target.Name) {
					continue
				}
				if err := visit(target); err != nil {
					return err
				}
			}
		}
		state[def.Name] = 2
		if !isSkippedPascal(cfg, def.Name) {
			order = append(order, def)
		}
		return nil
	}
	for _, def := range s.Defs {
		if isSkippedPascal(cfg, def.Name) {
			continue
		}
		if err := visit(def); err != nil {
			return nil, err
		}
	}
	return order, nil
}

func isSkippedPascal(cfg *PascalConfig, defName string) bool {
	for _, name := range cfg.Skip {
		if name == defName {
			return true
		}
	}
	return false
}

func pascalType(cfg *PascalConfig, p *Property) (string, error) {
	switch p.Type {
	case "":
		return "TJSONData", nil
	case "string":
		return "string", nil
	case "boolean":
		return "Boolean", nil
	case "integer":
		return "Int64", nil
	case "number":
		return "Double", nil
	case "object":
		return cfg.Types[refName(p.Ref)].Name, nil
	case "array":
		if p.ItemsRef != "" {
			return "array of " + cfg.Types[refName(p.ItemsRef)].Name, nil
		}
		switch p.ItemsType {
		case "string":
			return "array of string", nil
		case "boolean":
			return "array of Boolean", nil
		case "integer":
			return "array of Int64", nil
		case "number":
			return "array of Double", nil
		}
	}
	return "", fmt.Errorf("无法映射到 Pascal 类型: type=%q", p.Type)
}

func pascalLocalVars(cfg *PascalConfig, def *Object) []string {
	for _, p := range def.Properties {
		if p.Type == "array" && p.ItemsRef != "" {
			return []string{"Data: TJSONData;", "I: Integer;"}
		}
	}
	return nil
}

func pascalFromJson(cfg *PascalConfig, def *Object, p *Property) ([]string, error) {
	key := "'" + p.Name + "'"
	field := pascalField(p.Name)
	switch p.Type {
	case "string":
		return []string{fmt.Sprintf("Result.%s := JsonStr(Value, %s);", field, key)}, nil
	case "boolean":
		return []string{fmt.Sprintf("Result.%s := JsonBool(Value, %s);", field, key)}, nil
	case "integer":
		return []string{fmt.Sprintf("Result.%s := JsonInt64(Value, %s);", field, key)}, nil
	case "number":
		return []string{fmt.Sprintf("Result.%s := JsonFloat(Value, %s);", field, key)}, nil
	case "object":
		name := cfg.Types[refName(p.Ref)].Name
		return []string{
			fmt.Sprintf("Result.%s := %sFromJson(Value);", field, name),
		}, nil
	case "array":
		if p.ItemsRef != "" {
			elem := cfg.Types[refName(p.ItemsRef)].Name
			return []string{
				fmt.Sprintf("Result.%s := nil;", field),
				fmt.Sprintf("Data := Value.Find(%s);", key),
				"if (Data <> nil) and (Data.JSONType = jtArray) then",
				"begin",
				fmt.Sprintf("  SetLength(Result.%s, Data.Count);", field),
				"  for I := 0 to Data.Count - 1 do",
				fmt.Sprintf(
					"    Result.%s[I] := %sFromJson(TJSONObject(TJSONArray(Data).Items[I]));",
					field, elem),
				"end;",
			}, nil
		}
		switch p.ItemsType {
		case "string":
			return []string{fmt.Sprintf("Result.%s := JsonStrArray(Value, %s);", field, key)}, nil
		case "boolean":
			return []string{fmt.Sprintf("Result.%s := JsonBoolArray(Value, %s);", field, key)}, nil
		case "integer":
			return []string{fmt.Sprintf("Result.%s := JsonIntArray(Value, %s);", field, key)}, nil
		case "number":
			return []string{fmt.Sprintf("Result.%s := JsonFloatArray(Value, %s);", field, key)}, nil
		}
	}
	return nil, fmt.Errorf("无法生成 FromJson: type=%q", p.Type)
}

