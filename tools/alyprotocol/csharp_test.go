func mustSchema(t *testing.T, raw string) *Schema {
	t.Helper()
	s, err := ParseSchema([]byte(raw))
	if err != nil {
		t.Fatalf("ParseSchema: %v", err)
	}
	return s
}

const renderTestSchema = `{
  "$schema": "http://json-schema.org/draft-07/schema#",
  "x-protocol-version": "1.0.0",
  "$defs": {
    "Output": {
      "type": "object",
      "description": "信封 <x> & y",
      "additionalProperties": false,
      "required": ["isSuccess", "errorMsg", "data"],
      "properties": {
        "isSuccess": {"type": "boolean", "description": "是否成功"},
        "errorMsg": {"type": "string", "description": "错误"},
        "data": {"description": "载荷"}
      }
    },
    "DownloadProgress": {
      "type": "object",
      "description": "进度",
      "additionalProperties": false,
      "required": ["index", "file_size", "status"],
      "properties": {
        "index": {"type": "integer", "description": "序号"},
        "file_size": {"type": "integer", "description": "大小"},
        "status": {"type": "string", "enum": ["BEGIN", "DONE"], "description": "状态"},
        "note": {"type": "string", "description": "备注"}
      }
    }
  }
}`

func renderTestConfig() *Config {
	return &Config{
		Types: map[string]TypeConfig{
			"Output": {
				Name:       "AlyResponse",
				Namespace:  "AlyClient.CSharpSDK.Models",
				Visibility: "public",
				Partial:    true,
			},
			"DownloadProgress": {
				Namespace:  "AlyClient.CSharpSDK",
				Visibility: "internal",
			},
		},
		Properties: map[string]PropOverride{
			"DownloadProgress.file_size": {Type: "double"},
		},
	}
}

func findFile(t *testing.T, files []GeneratedFile, name string) GeneratedFile {
	t.Helper()
	for _, f := range files {
		if f.Name == name {
			return f
		}
	}
	t.Fatalf("generated file %q not found (got %v)", name, fileNames(files))
	return GeneratedFile{}
}

func fileNames(files []GeneratedFile) []string {
	names := make([]string, len(files))
	for i, f := range files {
		names[i] = f.Name
	}
	return names
}

func TestRenderKeepsSchemaOrderAndMapsTypes(t *testing.T) {
	s := mustSchema(t, renderTestSchema)
	files, err := Render(s, renderTestConfig())
	if err != nil {
		t.Fatal(err)
	}
	if len(files) != 2 || files[0].Name != "AlyResponse.g.cs" || files[1].Name != "DownloadProgress.g.cs" {
		t.Fatalf("file order = %v", fileNames(files))
	}

	env := string(findFile(t, files, "AlyResponse.g.cs").Content)
	for _, want := range []string{
		"public partial class AlyResponse",
		"namespace AlyClient.CSharpSDK.Models",
		"using Newtonsoft.Json;",
		`[JsonProperty("isSuccess")]`,
		"public bool IsSuccess { get; set; }",
		"public string ErrorMsg { get; set; }",
		"&lt;x&gt; &amp; y",
	} {
		if !strings.Contains(env, want) {
			t.Errorf("AlyResponse missing %q\n%s", want, env)
		}
	}
	if strings.Contains(env, `JsonProperty("data")`) || strings.Contains(env, "public object") {
		t.Errorf("AlyResponse must not generate the untyped data property\n%s", env)
	}

	prog := string(findFile(t, files, "DownloadProgress.g.cs").Content)
	for _, want := range []string{
		"internal class DownloadProgress",
		"namespace AlyClient.CSharpSDK",
		"public long Index { get; set; }",
		"public double FileSize { get; set; }",
		"public string Status { get; set; }",
		"public string Note { get; set; }",
	} {
		if !strings.Contains(prog, want) {
			t.Errorf("DownloadProgress missing %q\n%s", want, prog)
		}
	}
	if strings.Contains(prog, "?") {
		t.Errorf("nullable syntax is not allowed (C# 5 / net40)\n%s", prog)
	}

	order := []string{"Index", "FileSize", "Status", "Note"}
	last := -1
	for _, name := range order {
		idx := strings.Index(prog, name+" { get; set; }")
		if idx < 0 || idx < last {
			t.Fatalf("property order broken at %s\n%s", name, prog)
		}
		last = idx
	}
}

func TestRenderIsDeterministicAndLF(t *testing.T) {
	s := mustSchema(t, renderTestSchema)
	a, err := Render(s, renderTestConfig())
	if err != nil {
		t.Fatal(err)
	}
	b, err := Render(s, renderTestConfig())
	if err != nil {
		t.Fatal(err)
	}
	if len(a) != len(b) {
		t.Fatal("file count differs")
	}
	for i := range a {
		if !bytes.Equal(a[i].Content, b[i].Content) {
			t.Fatalf("%s not deterministic", a[i].Name)
		}
		if bytes.Contains(a[i].Content, []byte("\r")) {
			t.Fatalf("%s contains CR", a[i].Name)
		}
		if bytes.HasPrefix(a[i].Content, []byte{0xEF, 0xBB, 0xBF}) {
			t.Fatalf("%s starts with UTF-8 BOM", a[i].Name)
		}
		if !bytes.HasPrefix(a[i].Content, []byte("// <auto-generated>")) {
			t.Fatalf("%s missing auto-generated header", a[i].Name)
		}
	}
}

func TestRenderRejectsUnknownConfigType(t *testing.T) {
	s := mustSchema(t, renderTestSchema)
	cfg := renderTestConfig()
	cfg.Types["Missing"] = TypeConfig{Namespace: "X"}
	if _, err := Render(s, cfg); err == nil {
		t.Fatal("expected error for unknown schema def in config")
	}
}

