package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"io"
	"os"
	"regexp"
	"sort"
	"strings"
)

// RustConfig 对应 tools/alyprotocol/rust.json。
type RustConfig struct {
	Types map[string]RustTypeConfig `json:"types"`
	Skip  []string                  `json:"skip"`
}

type RustTypeConfig struct {
	Name string `json:"name"`
}

var rustIdentRe = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_]*$`)

func (c *RustConfig) normalize() error {
	for defName, tc := range c.Types {
		if tc.Name == "" {
			tc.Name = defName
		}
		if !rustIdentRe.MatchString(tc.Name) {
			return fmt.Errorf("类型 %s 的 Rust 名称 %q 不是合法标识符", defName, tc.Name)
		}
		c.Types[defName] = tc
	}
	for _, name := range c.Skip {
		if !rustIdentRe.MatchString(name) {
			return fmt.Errorf("skip 含非法定义名 %q", name)
		}
	}
	return nil
}

// LoadRustConfig 严格读取 Rust 生成配置。
func LoadRustConfig(path string) (*RustConfig, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("读取配置 %s: %v", path, err)
	}
	dec := json.NewDecoder(bytes.NewReader(data))
	dec.DisallowUnknownFields()
	var cfg RustConfig
	if err := dec.Decode(&cfg); err != nil {
		return nil, fmt.Errorf("解析配置 %s: %v", path, err)
	}
	var extra struct{}
	if err := dec.Decode(&extra); err != io.EOF {
		return nil, fmt.Errorf("配置 %s 含多余内容", path)
	}
	if err := cfg.normalize(); err != nil {
		return nil, fmt.Errorf("配置 %s: %v", path, err)
	}
	return &cfg, nil
}

// RenderRust 生成 models_gen.rs。
func RenderRust(s *Schema, cfg *RustConfig) (GeneratedFile, error) {
	if err := cfg.normalize(); err != nil {
		return GeneratedFile{}, err
	}
	if err := validateRustConfig(s, cfg); err != nil {
		return GeneratedFile{}, err
	}

	var b strings.Builder
	b.WriteString("// Code generated by tools/alyprotocol from spec/aly-protocol.schema.json. DO NOT EDIT.\n")
	b.WriteString("// Regenerate: cd tools/alyprotocol && go run . -write\n\n")
	b.WriteString("use serde::Deserialize;\n\n")

	first := true
	for _, def := range s.Defs {
		if isSkippedRust(cfg, def.Name) {
			continue
		}
		if !first {
			b.WriteString("\n")
		}
		first = false
		tc := cfg.Types[def.Name]

		if strings.TrimSpace(def.Description) != "" {
			b.WriteString("/// " + strings.ReplaceAll(def.Description, "\n", "\n/// ") + "\n")
		}
		b.WriteString("#[derive(Debug, Clone, PartialEq, Deserialize)]\n")
		fmt.Fprintf(&b, "pub struct %s {\n", tc.Name)
		for _, p := range def.Properties {
			if strings.TrimSpace(p.Description) != "" {
				b.WriteString("    /// " + strings.ReplaceAll(p.Description, "\n", "\n    /// ") + "\n")
			}
			if !def.IsRequired(p.Name) {
				b.WriteString("    #[serde(default)]\n")
			}
			typ, err := rustType(cfg, p, !def.IsRequired(p.Name))
			if err != nil {
				return GeneratedFile{}, fmt.Errorf("%s.%s: %v", def.Name, p.Name, err)
			}
			fmt.Fprintf(&b, "    pub %s: %s,\n", p.Name, typ)
		}
		b.WriteString("}\n")

		for _, p := range def.Properties {
			if len(p.Enum) == 0 {
				continue
			}
			fmt.Fprintf(&b, "\nimpl %s {\n", tc.Name)
			for _, v := range p.Enum {
				fmt.Fprintf(&b, "    pub const %s: &'static str = %q;\n", rustEnumConst(p.Name, v), v)
			}
			b.WriteString("}\n")
		}
	}

	return GeneratedFile{Name: "models_gen.rs", Content: []byte(b.String())}, nil
}

func validateRustConfig(s *Schema, cfg *RustConfig) error {
	skip := make(map[string]bool, len(cfg.Skip))
	for _, name := range cfg.Skip {
		if s.Def(name) == nil {
			return fmt.Errorf("Rust 配置 skip 了不存在的定义 %q", name)
		}
		if _, both := cfg.Types[name]; both {
			return fmt.Errorf("定义 %q 不能同时出现在 types 和 skip 中", name)
		}
		skip[name] = true
	}
	for defName := range cfg.Types {
		if s.Def(defName) == nil {
			return fmt.Errorf("Rust 配置引用了 schema 中不存在的定义 %q", defName)
		}
	}
	var missing []string
	for _, defName := range s.DefNames() {
		if _, ok := cfg.Types[defName]; ok || skip[defName] {
			continue
		}
		missing = append(missing, defName)
	}
	if len(missing) > 0 {
		sort.Strings(missing)
		return fmt.Errorf("schema 定义未生成 Rust 类型也未 skip: %s", strings.Join(missing, ", "))
	}
	return nil
}

func isSkippedRust(cfg *RustConfig, defName string) bool {
	for _, name := range cfg.Skip {
		if name == defName {
			return true
		}
	}
	return false
}

func rustType(cfg *RustConfig, p *Property, optional bool) (string, error) {
	var base string
	if len(p.Enum) > 0 {
		base = "String"
	} else {
		switch p.Type {
		case "":
			base = "serde_json::Value"
		case "string":
			base = "String"
		case "boolean":
			base = "bool"
		case "integer":
			base = "i64"
		case "number":
			base = "f64"
		case "object":
			return withOption(cfg.Types[refName(p.Ref)].Name, optional), nil
		case "array":
			var elem string
			if p.ItemsRef != "" {
				elem = cfg.Types[refName(p.ItemsRef)].Name
			} else {
				switch p.ItemsType {
				case "string":
					elem = "String"
				case "boolean":
					elem = "bool"
				case "integer":
					elem = "i64"
				case "number":
					elem = "f64"
				default:
					return "", fmt.Errorf("不支持的数组元素类型 %q", p.ItemsType)
				}
			}
			return withOption("Vec<"+elem+">", optional), nil
		default:
			return "", fmt.Errorf("无法映射到 Rust 类型: type=%q", p.Type)
		}
	}
	return withOption(base, optional), nil
}

func withOption(typ string, optional bool) string {
	if optional {
		return "Option<" + typ + ">"
	}
	return typ
}

func rustEnumConst(propName, value string) string {
	return strings.ToUpper(propName) + "_" + strings.ToUpper(value)
}
