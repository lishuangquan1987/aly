package main

import (
	"os"
	"strings"
	"testing"
)

const tsTestSchema = `{"$schema":"http://json-schema.org/draft-07/schema#","x-protocol-version":"1.0.0","$defs":{
"Output":{"type":"object","description":"信封","additionalProperties":false,
 "required":["isSuccess","errorMsg","data"],
 "properties":{"isSuccess":{"type":"boolean","description":"成功"},"errorMsg":{"type":"string"},
 "data":{"description":"载荷"}}},
"Item":{"type":"object","description":"条目","additionalProperties":false,
 "required":["path"],"properties":{"path":{"type":"string"}}},
"Data":{"type":"object","description":"数据 */ 逃逸","additionalProperties":false,
 "required":["status","count","items"],
 "properties":{
  "status":{"type":"string","enum":["BEGIN","DONE"],"description":"状态"},
  "count":{"type":"integer","description":"数量"},
  "optional_note":{"type":"string","description":"可选"},
  "items":{"type":"array","description":"条目数组","items":{"$ref":"#/$defs/Item"}},
  "tags":{"type":"array","description":"标签","items":{"type":"string"}}}}}}`

func tsTestConfig() *TSConfig {
	return &TSConfig{Types: map[string]TSTypeConfig{
		"Output": {Name: "AlyOutput"},
		"Item":   {},
		"Data":   {},
	}}
}

func TestRenderTSGeneratesInterfaces(t *testing.T) {
	s := mustSchema(t, tsTestSchema)
	file, err := RenderTS(s, tsTestConfig())
	if err != nil {
		t.Fatal(err)
	}
	if file.Name != "models.ts" {
		t.Fatalf("file name = %q", file.Name)
	}
	out := string(file.Content)
	for _, want := range []string{
		"// <auto-generated>",
		"export interface AlyOutput {",
		"export interface Item {",
		"export interface Data {",
		"isSuccess: boolean;",
		"data: unknown;",
		`status: "BEGIN" | "DONE";`,
		"count: number;",
		"optional_note?: string;",
		"items: Item[];",
		"tags?: string[];",
		"*\\/ 逃逸",
	} {
		if !strings.Contains(out, want) {
			t.Errorf("missing %q in:\n%s", want, out)
		}
	}
}

func TestRenderTSRequiresCoverage(t *testing.T) {
	s := mustSchema(t, tsTestSchema)
	cfg := &TSConfig{Types: map[string]TSTypeConfig{"Output": {}}}
	if _, err := RenderTS(s, cfg); err == nil {
		t.Fatal("expected coverage error for missing defs")
	}
}

func TestRenderTSRejectsUnknownType(t *testing.T) {
	s := mustSchema(t, tsTestSchema)
	cfg := tsTestConfig()
	cfg.Types["Missing"] = TSTypeConfig{}
	if _, err := RenderTS(s, cfg); err == nil {
		t.Fatal("expected error for unknown def")
	}
}

func TestLoadTSConfigDefaults(t *testing.T) {
	dir := t.TempDir()
	path := dir + "/ts.json"
	if err := os.WriteFile(path, []byte(`{"types":{"Data":{}},"extra":1}`), 0o600); err != nil {
		t.Fatal(err)
	}
	if _, err := LoadTSConfig(path); err == nil {
		t.Fatal("expected unknown-field error")
	}
	if err := os.WriteFile(path, []byte(`{"types":{"Data":{}}}`), 0o600); err != nil {
		t.Fatal(err)
	}
	cfg, err := LoadTSConfig(path)
	if err != nil {
		t.Fatal(err)
	}
	if cfg.Types["Data"].Name != "Data" {
		t.Fatalf("default name = %q", cfg.Types["Data"].Name)
	}
}
